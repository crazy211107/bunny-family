const fs=require('fs');
const path=require('path');
const esbuild=require('esbuild');
const root=path.resolve(__dirname,'..');
// The native renderer has device fallbacks and editor features beyond the old
// Web renderer. Never overwrite that maintained implementation with this legacy builder.
const current=fs.readFileSync(path.join(root,'miniprogram/utils/painter.js'),'utf8');
if(!current.startsWith('// Generated by scripts/build-native-painter.cjs')){
  throw new Error('原生 painter.js 为独立维护版本；旧 Web 生成器已停用，避免覆盖原生调色、画笔与工坊功能。');
}
let source=fs.readFileSync(path.join(root,'src/painter.js'),'utf8');
const nativeRound='context.moveTo(x+radius,y);context.lineTo(x+width-radius,y);context.quadraticCurveTo(x+width,y,x+width,y+radius);context.lineTo(x+width,y+height-radius);context.quadraticCurveTo(x+width,y+height,x+width-radius,y+height);context.lineTo(x+radius,y+height);context.quadraticCurveTo(x,y+height,x,y+height-radius);context.lineTo(x,y+radius);context.quadraticCurveTo(x,y,x+radius,y);context.closePath();';
if(!source.includes('context.roundRect(x, y, width, height, radius);'))throw new Error('Painter round() contract changed');
source=source.replace('context.roundRect(x, y, width, height, radius);',nativeRound);
source=source.replace('else if (typeof OffscreenCanvas !== "undefined")','else if (typeof wx !== "undefined" && wx.createOffscreenCanvas)\n    snapshot = wx.createOffscreenCanvas({type:"2d",width:canvas.width,height:canvas.height});\n  else if (typeof OffscreenCanvas !== "undefined")');
const output=esbuild.transformSync(source,{format:'cjs',target:'es2018',legalComments:'none'}).code;
fs.writeFileSync(path.join(root,'miniprogram/utils/painter.js'),'// Generated by scripts/build-native-painter.cjs from the shared renderer.\n'+output);
console.log('Native Canvas renderer generated.');
